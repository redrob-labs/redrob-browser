#!/usr/bin/env python3
"""Rewrite the packaging's key.include from a Redrob public signing key.

WHY THIS EXISTS. Upstream's key.include ships Google Inc's Linux Packages Signing Authority key
(EB4C1BFD4F042F6DDDCCEC917721F63BD38B4796), because upstream's package is Chrome and that is Chrome's key. Our
fork inherited it, so an installed redrob-browser wrote GOOGLE's key to /usr/share/keyrings/redrob-browser.gpg and
pointed apt at dl.google.com. That is not a cosmetic branding miss: it is the security-critical half of the
package speaking for someone else.

It is now empty by default, and apt.include refuses to configure any repository while it is -- no auto-update is a
documented gap, whereas a foreign repository and a foreign key on a user's machine is a defect. This script is how
the channel gets turned on: give it the ARMOURED PUBLIC key that matches whatever signs the repository, and the
next package configures apt for real.

  scripts/update_signing_key.py branding/redrob-signing-key.asc

The PUBLIC key only. It is public by definition -- it is what a user pins -- so unlike the private half it is safe
in this repository and belongs in the package. Passing a private key here would put a secret in a patch file; the
script refuses anything that looks like one rather than trusting the filename.
"""
from __future__ import annotations

import base64
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
KEY_INCLUDE = ROOT / "chromium" / "src" / "chrome" / "installer" / "linux" / "common" / "key.include"

TEMPLATE = """# Generated by scripts/update_signing_key.py. Do not edit directly.
#
# Redrob: EMPTY means the package configures NO apt repository and installs NO keyring -- see apt.include, which
# refuses rather than proceeding. Upstream ships Google's signing key here; a fork that inherited it would put
# Google's key and Google's repository on every machine that installed this package.
{comment}PGP_KEY_DATA=$(cat <<KEYDATA
{payload}KEYDATA
)
"""


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    source = pathlib.Path(sys.argv[1])
    if not source.exists():
        print(f"no such key file: {source}", file=sys.stderr)
        return 1
    text = source.read_text(encoding="utf-8")
    if "PRIVATE KEY" in text:
        print("that is a PRIVATE key. Only the public half belongs in a package; the private half must never "
              "be in this repository.", file=sys.stderr)
        return 1
    if "BEGIN PGP PUBLIC KEY BLOCK" not in text:
        print("that does not look like an ASCII-armoured PGP public key.", file=sys.stderr)
        return 1

    # The package base64-decodes this into a BINARY keyring, so the armour has to be converted rather than
    # pasted. export-minimal for the same reason upstream uses it: signatures and third-party certifications are
    # not needed to verify a repository and make the package larger for nothing.
    with tempfile.TemporaryDirectory(prefix="redrob-key-") as tmp:
        home = pathlib.Path(tmp)
        home.chmod(0o700)
        env = {"GNUPGHOME": str(home), "PATH": "/usr/bin:/bin"}
        subprocess.run(["gpg", "--batch", "--import"], env=env, input=text, text=True,
                       check=True, capture_output=True)
        listing = subprocess.run(["gpg", "--batch", "--list-keys", "--with-colons"], env=env,
                                 text=True, capture_output=True, check=True).stdout
        fingerprints = [line.split(":")[9] for line in listing.splitlines() if line.startswith("fpr:")]
        if not fingerprints:
            print("that key file imported nothing.", file=sys.stderr)
            return 1
        keyring = subprocess.run(["gpg", "--batch", "--export", "--export-options", "export-minimal",
                                  fingerprints[0]], env=env, capture_output=True, check=True).stdout

    encoded = base64.b64encode(keyring).decode()
    payload = "\n".join(encoded[i:i + 64] for i in range(0, len(encoded), 64)) + "\n"
    KEY_INCLUDE.write_text(TEMPLATE.format(comment=f"# key {fingerprints[0]}\n", payload=payload), encoding="utf-8")
    print(f"key.include now carries {fingerprints[0]} ({len(keyring)} bytes)")
    print("run `./scripts/redrob.py export` to regenerate the patch, then rebuild the package")
    return 0


if __name__ == "__main__":
    sys.exit(main())
