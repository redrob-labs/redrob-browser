# Write the WiX v4 fragment that installs every file under -Source into INSTALLFOLDER, keeping the
# folder layout (the GStreamer plugins in lib\gstreamer-1.0 and so on). Used by
# .github/workflows/release.yml before `wix build` with installer/windows/redrob-browser.wxs.
#
#   pwsh installer/windows/payload.ps1 -Source dist/app -Output dist/payload.wxs
#
# One component per folder, so a per-user install stays valid (ICE38, ICE64): each holds the
# folder's files, a RemoveFolder, and an HKCU value as its key path. Ids and component GUIDs are
# derived from the relative path, so the same file keeps the same component across releases.
param(
  [Parameter(Mandatory = $true)][string]$Source,
  [Parameter(Mandatory = $true)][string]$Output
)
$ErrorActionPreference = 'Stop'

$root = (Resolve-Path $Source).Path.TrimEnd('\')
# Namespace for the name-based component GUIDs. Fixed: changing it reissues every component.
$namespace = [guid]'D6160AF5-09C6-4683-8CF1-489E95EEEAB1'
$md5 = [System.Security.Cryptography.MD5]::Create()

function Get-Hash([string]$text) {
  $bytes = $md5.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($text.ToLowerInvariant()))
  -join ($bytes | ForEach-Object { $_.ToString('x2') })
}

# RFC 4122 version 3 (MD5, name-based) UUID of $name in $namespace.
function Get-NameGuid([string]$name) {
  $ns = $namespace.ToByteArray()
  # .NET stores the first three fields little-endian; RFC 4122 hashes them big-endian.
  [Array]::Reverse($ns, 0, 4); [Array]::Reverse($ns, 4, 2); [Array]::Reverse($ns, 6, 2)
  [byte[]]$data = $ns + [System.Text.Encoding]::UTF8.GetBytes($name.ToLowerInvariant())
  [byte[]]$h = $md5.ComputeHash($data)
  $h[6] = ($h[6] -band 0x0F) -bor 0x30
  $h[8] = ($h[8] -band 0x3F) -bor 0x80
  [Array]::Reverse($h, 0, 4); [Array]::Reverse($h, 4, 2); [Array]::Reverse($h, 6, 2)
  ([guid]::new([byte[]]$h)).ToString().ToUpperInvariant()
}

function Esc([string]$s) { [System.Security.SecurityElement]::Escape($s) }

function Get-Rel([string]$path) {
  if ($path.Length -le $root.Length) { return '' }
  $path.Substring($root.Length + 1)
}

function Get-DirId([string]$rel) {
  if ($rel -eq '') { return 'INSTALLFOLDER' }
  'dir_' + (Get-Hash "dir:$rel").Substring(0, 24)
}

$dirXml = New-Object System.Text.StringBuilder
$cmpXml = New-Object System.Text.StringBuilder

function Add-Dir([string]$path, [int]$depth) {
  $rel = Get-Rel $path
  $dirId = Get-DirId $rel
  $pad = '  ' * $depth
  foreach ($sub in Get-ChildItem -LiteralPath $path -Directory | Sort-Object Name) {
    $subId = Get-DirId (Get-Rel $sub.FullName)
    [void]$dirXml.AppendLine("$pad<Directory Id=`"$subId`" Name=`"$(Esc $sub.Name)`">")
    Add-Dir $sub.FullName ($depth + 1)
    [void]$dirXml.AppendLine("$pad</Directory>")
  }

  $h = (Get-Hash "cmp:$rel").Substring(0, 24)
  $guid = Get-NameGuid "component:$rel"
  [void]$cmpXml.AppendLine("      <Component Id=`"cmp_$h`" Directory=`"$dirId`" Guid=`"$guid`">")
  foreach ($file in Get-ChildItem -LiteralPath $path -File | Sort-Object Name) {
    $fid = 'fil_' + (Get-Hash ("file:" + (Get-Rel $file.FullName))).Substring(0, 24)
    [void]$cmpXml.AppendLine("        <File Id=`"$fid`" Source=`"$(Esc $file.FullName)`" />")
  }
  [void]$cmpXml.AppendLine("        <RemoveFolder Id=`"rmf_$h`" On=`"uninstall`" />")
  $key = if ($rel -eq '') { '.' } else { $rel }
  [void]$cmpXml.AppendLine("        <RegistryValue Root=`"HKCU`" Key=`"Software\Redrob\Redrob Browser\Files`" Name=`"$(Esc $key)`" Type=`"integer`" Value=`"1`" KeyPath=`"yes`" />")
  [void]$cmpXml.AppendLine("      </Component>")
}

Add-Dir $root 3

$xml = @"
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by installer/windows/payload.ps1 from $(Esc $root). Do not edit. -->
<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">
  <Fragment>
    <DirectoryRef Id="INSTALLFOLDER">
$($dirXml.ToString().TrimEnd())
    </DirectoryRef>
    <ComponentGroup Id="Payload">
$($cmpXml.ToString().TrimEnd())
    </ComponentGroup>
  </Fragment>
</Wix>
"@
New-Item -ItemType Directory -Force (Split-Path -Parent $Output) | Out-Null
Set-Content -LiteralPath $Output -Value $xml -Encoding utf8
Write-Host "wrote $Output"
